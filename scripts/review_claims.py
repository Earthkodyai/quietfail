import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)

FILES = ["thesis/THESIS_TH.md", "REPORT.md", "README.md", "CLAUDE.md",
         "slides/proposal.html"]

# ข้ออ้างที่ถอน/ลดระดับไปแล้ว พร้อมความจริงล่าสุด
WITHDRAWN = [
    (r"probes\s*=?\s*5[^\n]{0,40}(สมบูรณ์|เต็ม|1\.0000)",
     "probes=5 ได้ recall สมบูรณ์ — บนข้อมูลจริงได้ 0.9068"),
    (r"ช้ากว่า\s*2\.2\s*เท่าโดยไม่ได้",
     "สูตรเอกสารช้ากว่า 2.2 เท่าโดยไม่ได้อะไร — ถอนแล้ว"),
    (r"คำเตือน[^\n]{0,30}(ดีที่สุด|กรณีที่ดี)",
     "คำเตือนออกกับกรณีที่ดีที่สุด — จริงเฉพาะบนสังเคราะห์"),
    (r"(เป็นเท็จ|ไม่เป็นความจริง)[^\n]{0,20}(low recall|ชุดนี้)",
     "DETAIL เป็นเท็จ — เป็นจริงบนข้อมูลจริง"),
    (r"ตาย\s*50%[^\n]{0,20}ได้\s*0|dead 50%[^\n]{0,20}\*\*0\*\*",
     "L02 หน้าผาที่ 50% — ไม่เกิดบนข้อมูลจริง"),
    (r"กลบความไม่แน่นอน(ได้)?หมดจด",
     "probes=5 กลบความไม่แน่นอนหมดจด — เหลือ 60.5% บนข้อมูลจริง"),
    (r"เอกสาร[^\n]{0,20}ผิด[^\n]{0,10}3 (ที่|จุด)",
     "เอกสารผิด 3 ที่ — ยืนยันได้ 1 ที่"),
    (r"\bn=1\b|1 โมเดล.{0,15}1 ครั้ง|ทดสอบครั้งเดียว",
     "RQ3 n=1 — ตอนนี้ 2 โมเดล 3 การเก็บ"),
    (r"อัตราการพลาด|ติดกับดักบ่อยแค่ไหน",
     "RQ3 เป็นอัตรา — ตอบได้แค่รูปแบบ (D20)"),
    # เพิ่ม 2026-07-31 — ถอน/แก้ในรอบทดสอบข้ามชุดข้อมูลและรอบอ่านซอร์ส
    (r"กลไก[^\n]{0,25}(ยังไม่ทราบ|ยังไม่รู้|ไม่ทราบ)",
     "กลไก I04 ยังไม่ทราบ — ซอร์สตอบแล้ว เป็นการสุ่มระดับชั้น (E41)"),
    (r"ตัด(สาเหตุ)?[^\n]{0,15}ออก[^\n]{0,10}(สอง|2)\s*(ประการ|สาเหตุ|ข้อ)",
     "ตัดออกได้ 2 สาเหตุ — เลิกใช้กรอบนี้แล้ว กลไกทราบจากซอร์ส (E41)"),
    (r"เพดาน[^\n]{0,20}ef_search[^\n]{0,10}พอดี(เป๊ะ)?",
     "เพดาน = ef_search พอดี — บนข้อมูลจริงเป็น 41 (ef+1)"),
    (r"\*\*14[–\-]41%",
     "RQ1 14–41% — ต้องระบุชุดข้อมูล บนข้อมูลจริง HNSW เสีย 0.65%"),
]

# ถ้าคำเหล่านี้อยู่ในรัศมี ±RADIUS บรรทัด แปลว่ามีคำกำกับแล้ว
QUALIFIER = re.compile(
    r"ถอน|ลดระดับ|เคยพูด|เคยอ้าง|เคยเขียน|ห้ามพูด|หักล้าง|ไม่จริง|"
    r"สังเคราะห์|เดิม|บนข้อมูลจริง|ข้ามชุดข้อมูล|🔴|⚠️")

# 6 บรรทัด ครอบคลุมกล่องเตือน 3 บรรทัด + บรรทัดว่าง + หัวตาราง
# ซึ่งเป็นระยะที่คนอ่านเห็นคำกำกับได้จริงโดยไม่ต้องเลื่อนจอ
RADIUS = 6


def paragraph_at(lines, i):
    """
    คืนย่อหน้าที่บรรทัด i อยู่ — ตัดที่บรรทัดว่างหรือหัวข้อ

    ⚠️ ทำไมต้องเป็นย่อหน้า ไม่ใช่รัศมีบรรทัด
       เดิมใช้รัศมี ±6 บรรทัดล้วน แล้ว **พลาดของจริง** — ข้อจำกัดข้อ 3 ในเล่ม
       เขียนว่า "กลไกยังไม่ทราบ" แต่คำว่า "สังเคราะห์" ในข้อ 2 ที่อยู่เหนือขึ้นไป
       ถูกนับเป็นคำกำกับ ทั้งที่เป็นคนละเรื่องกันสิ้นเชิง (พบตอนทวนเล่ม 2026-07-31)
       ตอนนี้จึงตัดที่ขอบย่อหน้า แล้วค่อยขยายด้วยรัศมีเป็นตัวช่วยรอง
    """
    a = i
    while a > 0 and lines[a - 1].strip() and not lines[a - 1].lstrip().startswith("#"):
        a -= 1
    b = i
    while b + 1 < len(lines) and lines[b + 1].strip() \
            and not lines[b + 1].lstrip().startswith("#"):
        b += 1
    return "\n".join(lines[a:b + 1])


def main():
    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass

    print("=" * 74)
    print("ทวนข้ออ้างที่ถอนแล้ว — ในเอกสารหลัก %d ไฟล์" % len(FILES))
    print("=" * 74)

    hits = 0
    for fn in FILES:
        if not os.path.exists(fn):
            continue
        lines = io.open(fn, encoding="utf-8").read().splitlines()
        for i, line in enumerate(lines):
            # คำกำกับต้องอยู่ **ย่อหน้าเดียวกัน** ถึงจะนับ
            if QUALIFIER.search(paragraph_at(lines, i)):
                continue
            for pat, what in WITHDRAWN:
                if re.search(pat, line):
                    # บอกด้วยว่าใกล้ๆ มีคำกำกับไหม เพื่อให้คนตัดสินได้เร็ว
                    near = "\n".join(lines[max(0, i - RADIUS): i + RADIUS + 1])
                    tag = "  (มีคำกำกับใกล้ๆ แต่คนละย่อหน้า)" \
                        if QUALIFIER.search(near) else ""
                    print("\n🔴 %s:%d%s" % (fn, i + 1, tag))
                    print("   ข้ออ้าง : %s" % what)
                    print("   บรรทัด  : %s" % line.strip()[:110])
                    hits += 1

    print()
    if hits == 0:
        print("✅ ไม่พบข้ออ้างที่ถอนแล้วโดยไม่มีคำกำกับ")
    else:
        print("พบ %d จุด — อ่านด้วยตาแล้วตัดสินว่าต้องแก้หรือเป็นผลบวกลวง" % hits)
    return 0        # ไม่คืน exit 1 เพราะผลบวกลวงเป็นเรื่องปกติของการค้นคำ


if __name__ == "__main__":
    sys.exit(main())
