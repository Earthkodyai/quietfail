-- ============================================================
-- นิยามกลางของ fingerprint — **แหล่งอ้างอิงเดียว** (E40)
--
-- ทำไมต้องมี
-- ----------
-- สูตรนี้เคยถูกเขียนซ้ำในไฟล์ต่างๆ กว่า 30 จุด แล้วเคลื่อนออกจากกันจริง —
-- `sql/real_load.sql` เขียนใหม่ด้วยตัวคั่น ',' ขณะที่ที่อื่นใช้ '|'
-- ผลคือ guard ยิงทันทีที่รันครั้งแรก **ทั้งที่ qf_corpus ไม่ได้เปลี่ยนแม้แต่แถวเดียว**
-- (ดู E40 · รูปแบบเดียวกับ E39 ที่ตัวเลขในเอกสารเคลื่อนออกจากกัน)
--
-- ตั้งแต่นี้ไป **โค้ดใหม่ทุกตัวต้องเรียกฟังก์ชันนี้ ห้ามเขียนสูตรเอง**
--
-- ⚠️ ห้ามแก้สูตรข้างในเด็ดขาด — ค่าที่ได้ผูกกับผลการทดลองทุกตัวในเล่ม
--    และกับ scripts/audit_baseline.json  ถ้าแก้ ผลเก่าทั้งหมดเทียบไม่ได้ทันที
--
-- ไฟล์เก่ากว่า 30 จุดยังเขียนสูตรเองอยู่ **ตั้งใจไม่แก้** เพราะเป็นสคริปต์
-- การทดลองที่ผ่านการตรวจแล้ว การไปแก้มีความเสี่ยงมากกว่าประโยชน์
-- `scripts/audit.py` มีหัวข้อตรวจว่าทุกจุดยังใช้ตัวคั่นเดียวกัน จึงกันการเคลื่อนได้อยู่แล้ว
-- ============================================================

CREATE OR REPLACE FUNCTION qf_fingerprint(p_table regclass, p_rows int DEFAULT 5000)
RETURNS text
LANGUAGE plpgsql
STABLE
AS $$
DECLARE
    fp text;
BEGIN
    EXECUTE format(
        'SELECT md5(string_agg(embedding::text, ''|'' ORDER BY id)) '
        'FROM (SELECT id, embedding FROM %s ORDER BY id LIMIT %s) s',
        p_table, p_rows)
    INTO fp;
    RETURN fp;
END $$;

COMMENT ON FUNCTION qf_fingerprint(regclass, int) IS
    'นิยามกลางของ fingerprint (E40) — md5 ของ embedding::text ต่อกันด้วย ''|'' '
    'เรียงตาม id · โค้ดใหม่ต้องเรียกตัวนี้ ห้ามเขียนสูตรเอง';
